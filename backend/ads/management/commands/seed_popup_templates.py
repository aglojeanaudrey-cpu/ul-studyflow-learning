class Command(BaseCommand):
    help = "Crée les 8 templates de popups par défaut (idempotent)."

    def handle(self, *args, **options):
        created_count = 0
        skipped_count = 0

        for tpl in TEMPLATES:
            existing = PopupTemplate.objects.filter(name=tpl['name']).first()
            if existing:
                skipped_count += 1
                continue

            PopupTemplate.objects.create(
                name=tpl['name'],
                description=tpl['description'],
                icon=tpl['icon'],
                is_system=tpl['is_system'],
                preset=tpl['preset'],
                created_by='system',
            )
            created_count += 1

        self.stdout.write(self.style.SUCCESS(
            f"✅ {created_count} template(s) créé(s), {skipped_count} déjà existant(s)."
        ))